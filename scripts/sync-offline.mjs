// Commit the generated snapshot so readers never need a build/server/install step.
import {readFileSync,writeFileSync} from 'node:fs';
import assert from 'node:assert/strict';
const read=path=>readFileSync(path,'utf8');
const papers=JSON.parse(read('data/papers.json'));
const strip=source=>source.replace(/^import .*;\r?\n/gm,'').replace(/^export /gm,'');
let data=strip(read('assets/js/data.js'));
const start=data.indexOf('async function loadPapers() {');
const next=data.indexOf('\nfunction element(',start);
assert.ok(start>=0 && next>start,'Review data module before generating offline snapshot');
data=data.slice(0,start)+'async function loadPapers() { return validatePapers(offlinePapers); }\n'+data.slice(next);
const snapshot=JSON.stringify(papers).replace(/</g,'\\u003c').replace(/\u2028/g,'\\u2028').replace(/\u2029/g,'\\u2029');
const output='// Generated by node scripts/sync-offline.mjs. Edit papers.json / source modules instead.\n'+
  '(async () => {\n"use strict";\nconst offlinePapers = '+snapshot+';\n'+data+'\n'+strip(read('assets/js/math.js'))+
  '\nif (document.querySelector("#paper")) {\n'+strip(read('assets/js/paper.js'))+'\n} else {\n'+strip(read('assets/js/app.js'))+'\n}\n})().catch(() => {\n'+
  'const status=document.querySelector("#load-status, #results-status");\nif(status){status.textContent="離線資料無法載入，請重新取得完整的 PaperNotes 資料夾。";status.classList.add("notice");}\n});\n';
if(process.argv.includes('--check')){
 assert.equal(read('assets/js/offline.js'),output,'Offline snapshot is stale: run node scripts/sync-offline.mjs');
 console.log('PASS: offline snapshot matches JSON and all shared source modules.');
}else {writeFileSync('assets/js/offline.js',output);console.log(`Updated offline reader with ${papers.length} papers.`);}
